/* Packs the Cloudflare Worker into one file: worker/dist/worker.js
   - inlines the admin page (app/admin.html + app/app.css + app/admin.js) so it is only served at your secret ADMIN_PATH
   - bundles the QR code generator
   Run: npm install && npm run build:worker
   Then paste worker/dist/worker.js into the Cloudflare dashboard editor (or use `wrangler deploy` in ./worker). */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

let html = read('app/admin.html');
const css = read('app/app.css');
const js = read('app/admin.js');
const swap = (from, to) => {
  if (!html.includes(from)) throw new Error('admin.html changed: could not find ' + from);
  html = html.replace(from, () => to);
};
swap('<link rel="stylesheet" href="/app/app.css">', `<style>\n${css}\n</style>`);
swap('<script src="/app/admin.js"></script>', `<script>\n${js.replace(/<\/script/gi, '<\\/script')}\n</script>`);

const gen = path.join(ROOT, 'worker', 'src', 'admin-page.generated.js');
fs.writeFileSync(gen, `// generated by scripts/build-worker.js from app/admin.html, app/app.css, app/admin.js; do not edit\nexport const ADMIN_PAGE = ${JSON.stringify(html)};\n`);

require('esbuild').buildSync({
  entryPoints: [path.join(ROOT, 'worker', 'src', 'worker.js')],
  outfile: path.join(ROOT, 'worker', 'dist', 'worker.js'),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  minify: false, legalComments: 'inline',
  banner: { js: "// Jackie's Studio delivery Worker: built by scripts/build-worker.js. Paste this whole file into Cloudflare.\n" },
});
console.log('[build] worker/dist/worker.js ready (' + Math.round(fs.statSync(path.join(ROOT, 'worker', 'dist', 'worker.js')).size / 1024) + ' KB)');
